function heroSlot(root, MU, onMode) {
  const { gsap } = MU;
  const words = Array.from(root.querySelectorAll('.hero-slot__word'));
  const modes = root.querySelector('[data-hero-modes]');
  const btns = modes ? Array.from(modes.querySelectorAll('.hero-modes__item')) : [];
  const pill = modes && modes.querySelector('.hero-modes__pill');
  let cur = 0, call = null, visible = true, started = false;

  const placePill = (i, instant) => {
    const b = btns[i];
    if (!b || !pill) return;
    modes.style.setProperty('--pill', HERO_MODE_VAR[i]);
    const vars = { x: b.offsetLeft, width: b.offsetWidth };
    if (instant || MU.reduced) gsap.set(pill, vars); else gsap.to(pill, Object.assign(vars, { duration: 0.7, ease: 'expo.out', overwrite: true }));
    btns.forEach((x, k) => { x.classList.toggle('is-on', k === i); x.setAttribute('aria-pressed', k === i ? 'true' : 'false'); });
  };

  gsap.set(words.slice(1), { yPercent: 110, autoAlpha: 0 });
  if (!MU.reduced) gsap.set(words[0], { yPercent: 110 });

  function show(i) {
    if (i === cur) return;
    const out = words[cur], inn = words[i];
    cur = i;
    if (MU.reduced) {
      gsap.set(out, { autoAlpha: 0 }); gsap.set(inn, { yPercent: 0, autoAlpha: 1 });
    } else {
      gsap.to(out, { yPercent: -110, skewY: -7, autoAlpha: 0, duration: 0.6, ease: 'power3.in', overwrite: true });
      gsap.fromTo(inn, { yPercent: 110, skewY: 7, autoAlpha: 1 }, { yPercent: 0, skewY: 0, duration: 1.05, ease: 'expo.out', delay: 0.22, overwrite: true, clearProps: 'transform' });
    }
    placePill(i);
    onMode(i);
  }
  const schedule = d => {
    if (call) call.kill();
    call = null;
    if (!visible || !started || MU.reduced) return;
    call = gsap.delayedCall(d, () => { show((cur + 1) % words.length); schedule(3.2); });
  };
  btns.forEach((b, i) => b.addEventListener('click', () => { show(i); schedule(7); }));

  return {
    intro() {
      placePill(0, true);
      onMode(0);
      if (!MU.reduced) gsap.to(words[0], { yPercent: 0, duration: 1.3, ease: 'expo.out', delay: 0.72, clearProps: 'transform' });
      started = true;
      schedule(4.2);
    },
    setVisible(v) { if (v === visible) return; visible = v; schedule(2.4); },
    relayout() { placePill(cur, true); }
  };
}

function heroTimers(root) {
  const clock = root.querySelector('[data-hero-clock]');
  const eta = root.querySelector('[data-hero-eta]');
  const pad = n => String(n).padStart(2, '0');
  let left = 3 * 86400 + 14 * 3600 + 22 * 60 + 9;   /* seconds until the demo train reaches Toshkent */
  let timer = null;
  const renderClock = () => {
    const d = new Date(Date.now() + 5 * 3600 * 1000);
    if (clock) clock.textContent = `${pad(d.getUTCHours())}:${pad(d.getUTCMinutes())}:${pad(d.getUTCSeconds())}`;
  };
  const renderEta = animate => {
    if (!eta) return;
    const d = Math.floor(left / 86400), h = Math.floor((left % 86400) / 3600), m = Math.floor((left % 3600) / 60), s = left % 60;
    eta.innerHTML = `${d} kun ${pad(h)}:${pad(m)}:<span class="hero-sec">${pad(s)}</span>`;
    if (animate && !MU.reduced) gsap.fromTo(eta.lastChild, { yPercent: -70, autoAlpha: 0 }, { yPercent: 0, autoAlpha: 1, duration: 0.45, ease: 'power3.out' });
  };
  const tick = () => { left = Math.max(0, left - 1); renderClock(); renderEta(true); };
  renderClock(); renderEta(false);
  return {
    run(on) {
      if (on && !timer) { renderClock(); timer = setInterval(tick, 1000); }
      else if (!on && timer) { clearInterval(timer); timer = null; }
    }
  };
}

