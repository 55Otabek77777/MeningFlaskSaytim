const heroVec = (lat, lon, r = 1, out = new THREE.Vector3()) => {
  const la = lat * HERO_DEG, lo = lon * HERO_DEG;
  return out.set(Math.cos(la) * Math.sin(lo) * r, Math.sin(la) * r, Math.cos(la) * Math.cos(lo) * r);
};

