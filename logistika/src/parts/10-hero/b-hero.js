let heroApi = null;
MU.part('hero', {
  init(root, MU) {
    const { gsap } = MU;
    const copy = root.querySelector('.hero-copy');
    const cardWrap = root.querySelector('.hero-card-wrap');
    const hud = root.querySelector('.hero-rail');
    const hudRows = hud ? Array.from(hud.querySelectorAll('.hero-rail__in > *')) : [];
    const cue = root.querySelector('.hero-cue');
    const fill = root.querySelector('.hero-card__fill');
    const pathFg = root.querySelector('.hero-card__path-fg');
    const pct = root.querySelector('[data-hero-pct]');

    /* lock each stat to its final width before the count-up renders "0" */
    root.querySelectorAll('.hero-stat__v').forEach(el => { el.style.minWidth = Math.ceil(el.getBoundingClientRect().width) + 'px'; });

    const globe = heroGlobe(root, MU);
    const slot = heroSlot(root, MU, m => { if (globe) globe.setMode(m); });
    const timers = heroTimers(root);

    /* initial (pre-reveal) states for the hand-made choreography */
    if (!MU.reduced) {
      gsap.set(hudRows, { autoAlpha: 0, y: -30 });
      gsap.set(fill, { width: '0%' });
      if (pathFg) gsap.set(pathFg, { strokeDashoffset: 100 });
      if (pct) pct.textContent = '0';
    } else {
      gsap.set(cue, { opacity: 1 });
      if (pathFg) gsap.set(pathFg, { strokeDashoffset: 32 });
    }

    /* pause loops offscreen */
    MU.onVisible(root, vis => {
      root.classList.toggle('is-inview', vis);
      timers.run(vis);
      slot.setVisible(vis);
    }, '0px');

    /* scroll choreography */
    MU.mm.add({
      wide: '(min-width: 901px) and (orientation: landscape), (min-width: 1101px)',
      narrow: '(max-width: 900px), (orientation: portrait) and (max-width: 1100px)'
    }, ctx => {
      const { wide } = ctx.conditions;
      const blur = { v: 0 };
      const setBlur = () => { copy.style.filter = blur.v > 0.02 ? `blur(${(blur.v * 12).toFixed(2)}px)` : ''; };
      const tl = gsap.timeline({
        defaults: { ease: 'none' },
        scrollTrigger: {
          trigger: root, start: 'top top', end: 'bottom top', scrub: wide ? 0.6 : true, invalidateOnRefresh: true,
          onUpdate: s => { if (globe) globe.setScroll(s.progress); }
        }
      });
      if (!MU.reduced) {
        if (wide) {
          tl.fromTo(copy, { y: 0, autoAlpha: 1 }, { y: () => -window.innerHeight * 0.22, autoAlpha: 0, ease: 'power1.in', duration: 0.62 }, 0)
            .fromTo(blur, { v: 0 }, { v: 1, ease: 'power2.in', duration: 0.62, onUpdate: setBlur }, 0)
            .fromTo(cardWrap, { y: 0, autoAlpha: 1 }, { y: () => -window.innerHeight * 0.34, autoAlpha: 0, ease: 'power1.in', duration: 0.55 }, 0)
            .fromTo(hud, { autoAlpha: 1 }, { autoAlpha: 0, duration: 0.3 }, 0)
            .fromTo(cue, { y: 0 }, { y: 40, duration: 0.25 }, 0);
        } else {
          tl.fromTo(hud, { autoAlpha: 1 }, { autoAlpha: 0, duration: 0.15 }, 0);
        }
      }
      tl.set({}, {}, 1);
      return () => { copy.style.filter = ''; };
    });

    heroApi = {
      reveal() {
        if (globe) globe.intro();
        slot.intro();
        if (MU.reduced) return;
        gsap.to(hudRows, { autoAlpha: 1, y: 0, duration: 1.2, stagger: 0.1, ease: 'expo.out', delay: 1.6 });
        gsap.to(cue, { opacity: 1, duration: 1, delay: 2.6 });
        const o = { v: 0 };
        gsap.timeline({ delay: 2.1 })
          .to(fill, { width: '68%', duration: 2.2, ease: 'power3.inOut' }, 0)
          .to(pathFg, { strokeDashoffset: 32, duration: 2.2, ease: 'power3.inOut' }, 0)
          .to(o, { v: 68, duration: 2.2, ease: 'power3.inOut', onUpdate: () => { if (pct) pct.textContent = Math.round(o.v); } }, 0);
      },
      relayout: () => slot.relayout()
    };
    window.addEventListener('resize', () => {
      if (heroApi) heroApi.relayout();
      root.querySelectorAll('.hero-stat__v').forEach(el => { el.style.minWidth = ''; });
    }, { passive: true });
  },
  reveal() { if (heroApi) heroApi.reveal(); }
});
