/* ------------------------------------------------------------------ geometry helpers */
function heroLandGeometry(sparse) {
  const L = window.muHeroLand;
  if (!L) return null;
  const land = atob(L.land), uz = atob(L.uz);
  const bit = (s, k) => (s.charCodeAt(k >> 3) >> (k & 7)) & 1;
  const rows = Math.round(180 / L.step);
  const pos = [], rnd = [], uzA = [];
  const v = new THREE.Vector3();
  let k = 0, li = 0;
  for (let i = 0; i < rows; i++) {
    const lat = -90 + (i + 0.5) * L.step;
    const n = Math.max(1, Math.round((360 * Math.cos(lat * Math.PI / 180)) / L.step));
    for (let j = 0; j < n; j++, k++) {
      if (!bit(land, k)) continue;
      const u = bit(uz, li++);
      if (sparse && (i % 2 || j % 2)) continue;
      heroVec(lat, -180 + (j + 0.5) * (360 / n), 1, v);
      pos.push(v.x, v.y, v.z); rnd.push(Math.random()); uzA.push(u);
    }
  }
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
  g.setAttribute('aRnd', new THREE.Float32BufferAttribute(rnd, 1));
  g.setAttribute('aUz', new THREE.Float32BufferAttribute(uzA, 1));
  return { geo: g, step: L.step * (sparse ? 2 : 1) };
}

function heroStars(count) {
  const pos = new Float32Array(count * 3), size = new Float32Array(count), rnd = new Float32Array(count), col = new Float32Array(count * 3);
  const tints = [new THREE.Color('#e4ecff'), new THREE.Color('#e4ecff'), new THREE.Color('#bfe9ff'), new THREE.Color('#9ff7ef'), new THREE.Color('#ffe3a8'), new THREE.Color('#c9bcff')];
  const v = new THREE.Vector3();
  for (let i = 0; i < count; i++) {
    v.set(Math.random() * 2 - 1, Math.random() * 2 - 1, Math.random() * 2 - 1);
    if (v.lengthSq() > 1 || v.lengthSq() < 0.01) { i--; continue; }
    v.normalize().multiplyScalar(34 + Math.random() * 46);
    pos.set([v.x, v.y, v.z], i * 3);
    const big = Math.random() < 0.012;
    size[i] = big ? 2.6 + Math.random() * 1.2 : 0.7 + Math.pow(Math.random(), 2.6) * 1.6;
    rnd[i] = Math.random();
    const c = tints[(Math.random() * tints.length) | 0];
    const b = big ? 1 : 0.55 + Math.random() * 0.45;
    col.set([c.r * b, c.g * b, c.b * b], i * 3);
  }
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.BufferAttribute(pos, 3));
  g.setAttribute('aSize', new THREE.BufferAttribute(size, 1));
  g.setAttribute('aRnd', new THREE.BufferAttribute(rnd, 1));
  g.setAttribute('aCol', new THREE.BufferAttribute(col, 3));
  return g;
}

/* circle (+ optional tick marks) in the XZ plane with an angle attribute for draw-in / trails */
function heroRingGeometry(r, { ticks = 0, major = 0, tickLen = 0.02, majorLen = 0.05, inner = 0 } = {}) {
  const pos = [], ang = [];
  const seg = 240;
  const P = (a, rr) => [Math.cos(a) * rr, 0, Math.sin(a) * rr];
  const circle = rr => {
    for (let i = 0; i < seg; i++) {
      const a0 = (i / seg) * Math.PI * 2, a1 = ((i + 1) / seg) * Math.PI * 2;
      pos.push(...P(a0, rr), ...P(a1, rr)); ang.push(i / seg, (i + 1) / seg);
    }
  };
  circle(r);
  if (inner) circle(inner);
  if (ticks) {
    for (let i = 0; i < ticks; i++) {
      const a = (i / ticks) * Math.PI * 2;
      const isMajor = major && i % major === 0;
      pos.push(...P(a, r), ...P(a, r + (isMajor ? majorLen : tickLen))); ang.push(i / ticks, i / ticks);
    }
  }
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
  g.setAttribute('aAng', new THREE.Float32BufferAttribute(ang, 1));
  return g;
}

